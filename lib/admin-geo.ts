export type LatLon = { lat: number; lon: number };

const CENTROIDS: Record<string, LatLon> = (() => {
  const out: Record<string, LatLon> = {};
  const t = TABLE.trim().split(/\s+/);
  for (let i = 0; i + 2 < t.length; i += 3) {
    out[t[i]] = { lat: Number(t[i + 1]), lon: Number(t[i + 2]) };
  }
  return out;
})();

export function centroidOf(code: string): LatLon | null {
  return CENTROIDS[code] ?? null;
}

// 🔴나라 이름은 표로 안 들고 브라우저·Node 에게 물어본다(Intl.DisplayNames).
//   240개 × 8개 언어를 손으로 적는 대신 런타임이 제 로케일로 답한다.
//   ⚠️아주 옛 런타임에는 없다 — 그때는 코드를 그대로 보여 준다(빈 칸보다 낫다).
let namer: Intl.DisplayNames | null | undefined;
export function countryName(code: string, locale = "ko"): string {
  if (namer === undefined) {
    try {
      namer = new Intl.DisplayNames([locale], { type: "region" });
    } catch {
      namer = null;
    }
  }
  try {
    return namer?.of(code) ?? code;
  } catch {
    return code;
  }
}

// 국기 이모지 — ISO2 두 글자를 지역표시기호로 옮기면 나온다. 표가 필요 없다.
export function flagOf(code: string): string {
  if (!/^[A-Z]{2}$/.test(code)) return "";
  return String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}
